#!/usr/bin/env python3
"""Convert the visual6502 netlist *data* files (segdefs.js, transdefs.js,
nodenames.js) into a C header.  The .js files are parsed strictly as text with
regular expressions; nothing is executed.

usage: python3 -I tools/convert_netlist.py data/visual6502 gen/netlist6502.h
"""
import os
import re
import sys


def parse_segdefs(text):
    # [ node, '+'|'-', layer, x, y, ... ],
    pull = {}
    inconsistent = 0
    for m in re.finditer(r"\[\s*(\d+)\s*,\s*'([+-])'", text):
        n, p = int(m.group(1)), m.group(2) == '+'
        if n in pull:
            if pull[n] != p:
                inconsistent += 1
            # visual6502 semantics: the first segment seen decides
            continue
        pull[n] = p
    return pull, inconsistent


def parse_transdefs(text):
    # ['t123', gate, c1, c2, [bbox], [geometry...] ],
    out = []
    for m in re.finditer(r"\[\s*'t(\d+)'\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,", text):
        out.append((int(m.group(1)), int(m.group(2)), int(m.group(3)), int(m.group(4))))
    return out


def parse_nodenames(text):
    # strip /* */ comments, then match  name: number  or "name": number
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    names = []
    for line in text.splitlines():
        line = line.split("//", 1)[0]
        m = re.match(r'\s*"?([^":\s]+)"?\s*:\s*(-?\d+)\s*,?\s*$', line)
        if m:
            names.append((m.group(1), int(m.group(2))))
    return names


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(os.path.join(src, "segdefs.js")) as f:
        pull, inconsistent = parse_segdefs(f.read())
    with open(os.path.join(src, "transdefs.js")) as f:
        trans = parse_transdefs(f.read())
    with open(os.path.join(src, "nodenames.js")) as f:
        names = parse_nodenames(f.read())

    maxnode = max(max(pull), max(max(t[1:]) for t in trans))
    nnodes = maxnode + 1
    pullups = sorted(n for n, p in pull.items() if p)
    named = {n: v for n, v in names}
    for req in ("vcc", "vss", "clk0", "rdy", "irq", "nmi", "res", "so", "rw", "sync"):
        if req not in named:
            sys.exit("missing node name %s" % req)

    with open(dst, "w") as f:
        f.write("/* GENERATED by tools/convert_netlist.py from visual6502 segdefs.js /\n")
        f.write("   transdefs.js / nodenames.js (www.visual6502.org, Greg James, Brian\n")
        f.write("   Silverman, Barry Silverman; segdefs/transdefs are CC BY-NC-SA 3.0).\n")
        f.write("   Do not edit. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define NET6502_NODES %d\n" % nnodes)
        f.write("#define NET6502_TRANSISTORS %d\n" % len(trans))
        f.write("#define NET6502_PULLUPS %d\n" % len(pullups))
        f.write("#define NET6502_NAMES %d\n\n" % len(names))
        f.write("/* node numbers that carry a pull-up ('+' in segdefs) */\n")
        f.write("static const uint16_t net6502_pullups[NET6502_PULLUPS] = {\n")
        for i in range(0, len(pullups), 16):
            f.write("  " + ",".join(str(x) for x in pullups[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("/* transistors: gate, c1, c2 (index = visual6502 tNNN number order of the file) */\n")
        f.write("static const uint16_t net6502_trans[NET6502_TRANSISTORS][3] = {\n")
        for i in range(0, len(trans), 6):
            f.write("  " + " ".join("{%d,%d,%d}," % t[1:] for t in trans[i:i + 6]) + "\n")
        f.write("};\n\n")
        f.write("typedef struct { const char *name; int node; } net6502_name_t;\n")
        f.write("static const net6502_name_t net6502_names[NET6502_NAMES] = {\n")
        for n, v in names:
            f.write('  {"%s",%d},\n' % (n.replace("\\", "\\\\"), v))
        f.write("};\n")
    print("netlist: %d nodes (max id %d), %d transistors, %d pull-ups, %d names, "
          "%d nodes with inconsistent segment pull flags"
          % (len(pull), maxnode, len(trans), len(pullups), len(names), inconsistent))


if __name__ == "__main__":
    main()
