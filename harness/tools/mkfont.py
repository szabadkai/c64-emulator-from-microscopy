ORDER = "@ABCDEFGHIJKLMNOPQRSTUVWXYZ[#]^<" + " !\"#$%&'()*+,-./0123456789:;<=>?"


def glyph_bytes(ch):
    rows = G[ch]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    out = [int("0" + r.replace('#', '1').replace('.', '0') + "00", 2) for r in rows]
    return out + [0]


def main():
    assert len(ORDER) == 64
    with open(sys.argv[1], "w") as f:
        f.write("; GENERATED by tools/mkfont.py - self-designed 8x8 font, screen codes 0..63\n")
        for code, ch in enumerate(ORDER):
            b = glyph_bytes(ch)
            f.write("        .byte " + ",".join("$%02X" % x for x in b) + "   ; %02d %s\n" % (code, ch))


if __name__ == "__main__":
    main()
