#!/usr/bin/env python3
"""ncc.py - compile the visual6502 netlist into C (see README.md).

usage: python3 -I ncc.py ../harness/gen/netlist6502.h gen/

Reads only the netlist header (the converted visual6502 data).  Writes
  gen/ccpu_net.h    sizes and pad/register node ids
  gen/ccpu_net.inc  tables + the compiled per-node switching code
which src/ccpu.c includes.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "tools"))
from netlist import Netlist  # noqa: E402


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    N = Netlist(src)
    nn, vss, vcc = N.nn, N.vss, N.vcc
    tt = N.trans
    # compact channel-transistor numbering in netsim's t order
    chidx = {t: k for k, t in enumerate(N.chan_trans)}
    nch = len(N.chan_trans)
    nslot = 2 * nch
    assert nslot < 32767
    sother = [0] * nslot
    init_on = []
    for k, t in enumerate(N.chan_trans):
        g, c1, c2 = tt[t]
        sother[2 * k] = c2       # slot 2k lives in c1's list, its far end is c2
        sother[2 * k + 1] = c1   # slot 2k+1 lives in c2's list
        init_on.append(1 if g == vcc else 0)
    assert max(N.gnd_init) < 256 and max(N.pwr_init) < 256

    os.makedirs(outdir, exist_ok=True)
    # ------------------------------------------------------------ header
    def nid(name):
        return N.byname.get(name, -1)
    with open(os.path.join(outdir, "ccpu_net.h"), "w") as f:
        f.write("/* GENERATED by ncc.py from %s - do not edit */\n#pragma once\n" % os.path.basename(src))
        f.write("#define CC_NN %d\n#define CC_NCH %d\n#define CC_NSLOT %d\n" % (nn, nch, nslot))
        f.write("#define CC_VSS %d\n#define CC_VCC %d\n" % (vss, vcc))
        f.write("#define CC_NT %d   /* transistors after netsim's clean-up */\n" % len(tt))
        for nm in ("clk0", "rdy", "irq", "nmi", "res", "so", "rw", "sync"):
            f.write("#define CC_N_%s %d\n" % (nm.upper(), nid(nm)))
        for bus, cnt in (("ab", 16), ("db", 8), ("a", 8), ("x", 8), ("y", 8), ("s", 8), ("p", 8),
                         ("pcl", 8), ("pch", 8), ("ir", 8)):
            f.write("#define CC_BUS_%s {%s}\n" % (bus.upper(), ",".join(str(nid("%s%d" % (bus, i))) for i in range(cnt))))
    # ------------------------------------------------------------ tables + code
    L = []
    w = L.append
    w("/* GENERATED by ncc.py from %s - do not edit.\n" % os.path.basename(src))
    w("   %d nodes, %d transistors (%d after netsim's clean-up), %d channel transistors */\n"
      % (nn, len(N.raw_trans), len(tt), nch))

    def arr(ctype, name, vals, per=24):
        w("static const %s %s[%d] = {\n" % (ctype, name, len(vals)))
        for i in range(0, len(vals), per):
            w("  " + ",".join(str(v) for v in vals[i:i + per]) + ",\n")
        w("};\n")
    arr("uint8_t", "CC_SIMPLE", N.simple)
    arr("uint8_t", "CC_ORIG_PULL", [2 if N.pullup[n] else 0 for n in range(nn)])
    arr("uint8_t", "CC_GND_INIT", N.gnd_init)
    arr("uint8_t", "CC_PWR_INIT", N.pwr_init)
    arr("uint16_t", "CC_SOTHER", sother)
    arr("uint8_t", "CC_CH_INIT_ON", init_on)
    arr("uint16_t", "CC_CH_T", N.chan_trans)   # netsim transistor index of each channel transistor
    # names
    w("static const struct { const char *name; int node; } CC_NAMES[%d] = {\n" % len(N.names))
    for a, b in N.names:
        w('  {"%s",%d},\n' % (a.replace("\\", "\\\\").replace('"', '\\"'), b))
    w("};\n")

    # slot s of netsim's numbering (2k / 2k+1) is index s+1 in ccpu's list
    # arrays (index 0 = end-of-list sentinel, CC_HB+n = head of node n)
    hb = 1 + nslot
    w("#define CC_HB %d\n" % hb)
    arr("uint16_t", "CC_SOTHER1", [0] + sother)

    has_pwr = set(d for g in N.gpwr for d in N.gpwr[g]) | set(n for n in range(nn) if N.pwr_init[n])

    def sv(d):
        # netsim simple_value(d): ngnd ? 0 : npwr ? 1 : pull-down ? 0 : pull-up ? 1 : charge
        return ("SV(c,%d)" if d in has_pwr else "SVNP(c,%d)") % d

    # Per-node switching code: netsim's set_node() for that node, unrolled,
    # with branch-free queue appends and list updates.
    w("#ifdef CCPU_UNROLLED\n")
    w("static void set_node(ccpu_t *restrict c, int m, int v) {\n")
    w("    uint16_t *restrict qout = c->q[c->qo];\n")
    w("    int nout = c->nout;\n")
    w("    const uint32_t st = c->ostamp;\n")
    w("    c->f[m] ^= 1;\n    STAT(c->st.changes++);\n")
    w("    switch ((m << 1) | v) {\n")
    for m in range(nn):
        gch = N.gchan.get(m, [])
        gg = N.ggnd.get(m, [])
        gp = N.gpwr.get(m, [])
        dp = N.dep.get(m, [])
        if not (gch or gg or gp or dp):
            continue
        for v in (1, 0):
            body = []
            if v:
                for t in gch:
                    k = chidx[t]
                    g_, c1, c2 = tt[t]
                    body.append("LINK(%d,%d); LINK(%d,%d); QC(%d, (c->f[%d] ^ c->f[%d]) & 1);"
                                % (2 * k + 1, c1, 2 * k + 2, c2, c1, c1, c2))
                for d in gg:
                    if N.simple[d]:
                        body.append("c->ngnd[%d]++; QC(%d, c->f[%d] & 1);" % (d, d, d))
                    else:
                        body.append("{ int e_ = c->ngnd[%d]++ == 0; QC(%d, e_); }" % (d, d))
                for d in gp:
                    if N.simple[d]:
                        body.append("c->npwr[%d]++; QC(%d, (c->ngnd[%d] == 0) != (c->f[%d] & 1));" % (d, d, d, d))
                    else:
                        body.append("{ int e_ = c->npwr[%d]++ == 0; QC(%d, e_); }" % (d, d))
            else:
                for t in gch:
                    k = chidx[t]
                    body.append("UNLINK(%d); UNLINK(%d);" % (2 * k + 1, 2 * k + 2))
                for d in gg:
                    if N.simple[d]:
                        body.append("c->ngnd[%d]--; QC(%d, %s != (c->f[%d] & 1));" % (d, d, sv(d), d))
                    else:
                        body.append("{ int e_ = --c->ngnd[%d] == 0; QC(%d, e_); }" % (d, d))
                for d in gp:
                    if N.simple[d]:
                        body.append("c->npwr[%d]--; QC(%d, %s != (c->f[%d] & 1));" % (d, d, sv(d), d))
                    else:
                        body.append("{ int e_ = --c->npwr[%d] == 0; QC(%d, e_); }" % (d, d))
                for d in dp:
                    body.append("QF(%d);" % d)
            w("    case %d: /* %s -> %d */\n" % ((m << 1) | v, N.name(m).replace("*/", "* /"), v))
            for b_ in body:
                w("        %s\n" % b_)
            w("        break;\n")
    w("    default: break;\n    }\n    c->nout = nout;\n}\n")
    w("#endif /* CCPU_UNROLLED */\n")

    # The same switching operations as compact tables (CCPU_TABLES): per
    # (node, new value) a block  [#gchan, (slot, c1, c2)...] [#ggnd, d|simple<<15 ...]
    # [#gpwr, d|simple<<15 ...] [#dep, d ...]  (dep only for value 0)
    fo, off = [], []
    for m in range(nn):
        for v in (0, 1):
            off.append(len(fo))
            gch = N.gchan.get(m, [])
            fo.append(len(gch))
            for t in gch:
                k = chidx[t]
                g_, c1, c2 = tt[t]
                fo += [2 * k + 1, c1, c2]
            for lst in (N.ggnd.get(m, []), N.gpwr.get(m, [])):
                fo.append(len(lst))
                fo += [d | (N.simple[d] << 15) for d in lst]
            dp = N.dep.get(m, []) if v == 0 else []
            fo.append(len(dp))
            fo += dp
    off.append(len(fo))
    assert nn < 32768 and len(fo) < 65536
    arr("uint16_t", "CC_FO_OFF", off)
    arr("uint16_t", "CC_FO", fo)
    with open(os.path.join(outdir, "ccpu_net.inc"), "w") as f:
        f.write("".join(L))

    # the levelized core (lcpu): straight-line code per clock phase
    import lgen
    ls = lgen.emit(N, outdir)
    print("ncc: lcpu PHI1: %d nodes fixed by CLK0, %d phase components, SCCs %s, %d self-gated"
          % (ls["phi1"][0], ls["phi1"][1], sorted(ls["phi1"][2], reverse=True), ls["phi1"][3]))
    print("ncc: lcpu PHI2: %d nodes fixed by CLK0, %d phase components, SCCs %s, %d self-gated"
          % (ls["phi2"][0], ls["phi2"][1], sorted(ls["phi2"][2], reverse=True), ls["phi2"][3]))
    print("ncc: lcpu cones: RDY/IRQ/NMI/RES %d components, D0-D7 %d components" % (ls["cone_ctl"], ls["cone_db"]))

    # statistics for the README
    comps = N.ccc()
    sizes = {}
    for cc in comps:
        sizes[len(cc)] = sizes.get(len(cc), 0) + 1
    print("ncc: %d nodes, %d transistors -> %d after clean-up (%d to VSS, %d to VCC, %d channel)"
          % (nn, len(N.raw_trans), len(tt), sum(len(v) for v in N.ggnd.values()),
             sum(len(v) for v in N.gpwr.values()), nch))
    print("ncc: %d channel-connected components; size histogram %s" % (len(comps), sorted(sizes.items())))


if __name__ == "__main__":
    main()
